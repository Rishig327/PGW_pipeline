def parse_date(value):
    value = str(value).strip()
    if not value:
        return None

    # Example: 02-OCT-14
    return datetime.strptime(value, "%d-%b-%y").strftime("%Y-%m-%dT00:00:00")


def build_rows(raw_data):
    rows = []

    lines = raw_data.strip().splitlines()

    # skip header
    for line_no, line in enumerate(lines[1:], start=2):
        line = line.strip()

        if not line:
            continue

        cols = line.split("\t")

        if len(cols) != 6:
            print(f"Skipping invalid line {line_no}: {line}")
            continue

        imsi_prefix, mvno, created_date, created_by, modified_date, modified_by = cols

        rows.append({
            "IMSI_PREFIX": imsi_prefix.replace("%", "").strip(),
            "MVNO": mvno.strip(),
            "CREATED_DATE": parse_date(created_date),
            "CREATED_BY": created_by.strip(),
            "MODIFIED_DATE": parse_date(modified_date),
            "MODIFIED_BY": modified_by.strip()
        })

    return rows


def insert_in_batches(table_id, rows, batch_size=500):
    total_inserted = 0

    for i in range(0, len(rows), batch_size):
        batch = rows[i:i + batch_size]

        errors = client.insert_rows_json(table_id, batch)

        if errors:
            print(f"Errors in batch starting at row {i + 1}:")
            print(errors)
        else:
            total_inserted += len(batch)
            print(f"Inserted batch: {len(batch)} rows")

    print(f"Completed. Total inserted: {total_inserted}")


